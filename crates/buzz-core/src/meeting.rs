//! Channel-owned context with organizer-authored meeting series.

use std::collections::HashSet;

use chrono::{
    DateTime, Datelike, Days, Duration, LocalResult, NaiveDate, NaiveDateTime, TimeZone, Timelike,
    Utc, Weekday,
};
use chrono_tz::Tz;
use nostr::{Event, EventId};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use crate::kind::KIND_CHANNEL_MEETING;

/// Current version of the channel-meeting JSON contract.
pub const MEETING_VERSION: u8 = 1;
/// Maximum UTF-8 byte length of a meeting title.
pub const MAX_MEETING_TITLE_BYTES: usize = 256;
/// Maximum serialized size of a meeting definition.
pub const MAX_MEETING_CONTENT_BYTES: usize = 8192;
/// Maximum number of explicitly skipped dates in one series.
pub const MAX_MEETING_SKIPPED_DATES: usize = 128;
/// Maximum number of occurrences generated by one request.
pub const MAX_MEETING_OCCURRENCES: usize = 32;

const MAX_LOOKAHEAD_DAYS: u64 = 1095;

/// Errors in a meeting definition, event envelope, or occurrence request.
#[derive(Debug, thiserror::Error, PartialEq, Eq)]
#[error("{0}")]
pub struct MeetingError(pub String);

/// Supported calendar recurrence rules, anchored on the first meeting's local date.
#[derive(Debug, Clone, Copy, Default, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum MeetingRecurrence {
    /// The meeting happens only on its first local date.
    #[default]
    Once,
    /// The meeting repeats every seven local calendar days.
    Weekly,
    /// The meeting repeats every fourteen local calendar days.
    Fortnightly,
    /// The meeting repeats Monday through Friday.
    Weekdays,
}

/// Lifecycle of a meeting series.
#[derive(Debug, Clone, Copy, Default, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum MeetingStatus {
    /// Future occurrences remain scheduled.
    #[default]
    Active,
    /// No future occurrences or nudges should be generated.
    Cancelled,
}

/// A meeting series stored as the content of a kind:30623 event.
#[derive(Debug, Clone, Deserialize, Serialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct MeetingDefinition {
    /// Wire contract version; currently 1.
    pub version: u8,
    /// Human-readable title, without control characters.
    pub title: String,
    /// First meeting's local wall-clock date and time, with minute precision.
    pub starts_at: NaiveDateTime,
    /// IANA timezone in which the wall-clock recurrence is evaluated.
    pub timezone: String,
    /// Elapsed duration, between 1 minute and 24 hours.
    pub duration_minutes: u16,
    /// Calendar recurrence, defaulting to a one-time meeting.
    #[serde(default)]
    pub recurrence: MeetingRecurrence,
    /// Current series lifecycle, defaulting to active.
    #[serde(default)]
    pub status: MeetingStatus,
    /// Opt-in shared-nudge lead time; absent means no channel nudge.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub nudge_minutes_before: Option<u16>,
    /// Local occurrence dates excluded without changing the series anchor.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub skipped_dates: Vec<NaiveDate>,
}

/// A concrete occurrence and its optional shared-nudge instant.
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct MeetingOccurrence {
    /// The occurrence's local date, stable across timezone offset changes.
    pub local_date: NaiveDate,
    /// Meeting start instant.
    pub starts_at: DateTime<Utc>,
    /// Meeting end instant, measured as elapsed duration from the start.
    pub ends_at: DateTime<Utc>,
    /// Nudge instant, if the organizer opted into a shared channel nudge.
    pub nudge_at: Option<DateTime<Utc>>,
}

/// A parsed meeting event with its channel-bound address.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ChannelMeeting {
    /// Channel owning the meeting context.
    pub channel_id: Uuid,
    /// Meeting UUID within the organizer's channel-bound address.
    pub meeting_id: Uuid,
    /// Validated meeting definition.
    pub definition: MeetingDefinition,
}

/// Optimistic-concurrency condition carried by a meeting write.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MeetingRevision {
    /// Legacy write using ordinary NIP-33 replacement ordering.
    Unconditional,
    /// Create only when the coordinate has no live head.
    NoHead,
    /// Replace only the named live head.
    Head(EventId),
}

/// Validate the optional meeting `expected-revision` tag.
pub fn meeting_revision(event: &Event) -> Result<MeetingRevision, MeetingError> {
    let mut tags = event.tags.iter().map(|tag| tag.as_slice()).filter(|parts| {
        parts
            .first()
            .is_some_and(|part| part == "expected-revision")
    });
    let Some(parts) = tags.next() else {
        return Ok(MeetingRevision::Unconditional);
    };
    if parts.len() != 2 || tags.next().is_some() {
        return Err(MeetingError(
            "meeting requires at most one two-element expected-revision tag".into(),
        ));
    }
    if parts[1] == "none" {
        return Ok(MeetingRevision::NoHead);
    }
    let revision = EventId::from_hex(&parts[1]).map_err(|_| {
        MeetingError("meeting expected-revision must be none or a hexadecimal event ID".into())
    })?;
    Ok(MeetingRevision::Head(revision))
}

impl MeetingDefinition {
    /// Validate the version, limits, timezone, first start, and skipped dates.
    pub fn validate(&self) -> Result<(), MeetingError> {
        if self.version != MEETING_VERSION {
            return Err(MeetingError("unsupported meeting version".into()));
        }
        if self.title.trim().is_empty()
            || self.title.len() > MAX_MEETING_TITLE_BYTES
            || self.title.chars().any(char::is_control)
        {
            return Err(MeetingError(
                "meeting title must contain 1–256 bytes and no control characters".into(),
            ));
        }
        if !(1..=1440).contains(&self.duration_minutes) {
            return Err(MeetingError(
                "meeting duration must be between 1 and 1440 minutes".into(),
            ));
        }
        if self
            .nudge_minutes_before
            .is_some_and(|lead| !(1..=1440).contains(&lead))
        {
            return Err(MeetingError(
                "channel nudge lead time must be between 1 and 1440 minutes".into(),
            ));
        }
        if self.starts_at.second() != 0 || self.starts_at.nanosecond() != 0 {
            return Err(MeetingError(
                "meeting start must have minute precision".into(),
            ));
        }
        let timezone = self.parse_timezone()?;
        if local_start(timezone, self.starts_at).is_none() {
            return Err(MeetingError(
                "first meeting falls in a nonexistent local time".into(),
            ));
        }
        if self.recurrence == MeetingRecurrence::Weekdays
            && matches!(self.starts_at.weekday(), Weekday::Sat | Weekday::Sun)
        {
            return Err(MeetingError(
                "a weekday meeting must start on a weekday".into(),
            ));
        }
        if self.skipped_dates.len() > MAX_MEETING_SKIPPED_DATES {
            return Err(MeetingError(
                "too many skipped meeting dates (maximum 128)".into(),
            ));
        }
        let mut unique_dates = HashSet::new();
        for date in &self.skipped_dates {
            if !self.matches_date(*date) || !unique_dates.insert(*date) {
                return Err(MeetingError(
                    "skipped dates must be distinct occurrence dates on or after the first meeting"
                        .into(),
                ));
            }
        }
        Ok(())
    }

    /// Return up to `limit` occurrences starting at or after `after`.
    ///
    /// Recurrences keep the requested local wall-clock time. A later occurrence
    /// in a daylight-saving gap is skipped; an ambiguous start uses its earlier
    /// UTC instant, so the repeated local hour never creates two occurrences.
    /// Work is bounded to three years and at most 32 returned occurrences.
    pub fn next_occurrences(
        &self,
        after: DateTime<Utc>,
        limit: usize,
    ) -> Result<Vec<MeetingOccurrence>, MeetingError> {
        self.validate()?;
        if !(1..=MAX_MEETING_OCCURRENCES).contains(&limit) {
            return Err(MeetingError(
                "occurrence limit must be between 1 and 32".into(),
            ));
        }
        if self.status == MeetingStatus::Cancelled {
            return Ok(Vec::new());
        }
        let timezone = self.parse_timezone()?;
        let first_date = self
            .starts_at
            .date()
            .max(after.with_timezone(&timezone).date_naive());
        let mut occurrences = Vec::with_capacity(limit);
        for day_offset in 0..=MAX_LOOKAHEAD_DAYS {
            let Some(date) = first_date.checked_add_days(Days::new(day_offset)) else {
                break;
            };
            if self.recurrence == MeetingRecurrence::Once && date > self.starts_at.date() {
                break;
            }
            if !self.matches_date(date) || self.skipped_dates.contains(&date) {
                continue;
            }
            let Some(starts_at) = local_start(timezone, date.and_time(self.starts_at.time()))
            else {
                continue;
            };
            if starts_at < after {
                continue;
            }
            let ends_at = starts_at
                .checked_add_signed(Duration::minutes(i64::from(self.duration_minutes)))
                .ok_or_else(|| {
                    MeetingError("meeting end is outside the supported date range".into())
                })?;
            let nudge_at = self
                .nudge_minutes_before
                .map(|lead| {
                    starts_at
                        .checked_sub_signed(Duration::minutes(i64::from(lead)))
                        .ok_or_else(|| {
                            MeetingError("meeting nudge is outside the supported date range".into())
                        })
                })
                .transpose()?;
            occurrences.push(MeetingOccurrence {
                local_date: date,
                starts_at,
                ends_at,
                nudge_at,
            });
            if occurrences.len() == limit {
                break;
            }
        }
        Ok(occurrences)
    }

    fn parse_timezone(&self) -> Result<Tz, MeetingError> {
        self.timezone
            .parse()
            .map_err(|_| MeetingError("meeting timezone must be a valid IANA timezone".into()))
    }

    fn matches_date(&self, date: NaiveDate) -> bool {
        let elapsed = date.signed_duration_since(self.starts_at.date()).num_days();
        if elapsed < 0 {
            return false;
        }
        match self.recurrence {
            MeetingRecurrence::Once => elapsed == 0,
            MeetingRecurrence::Weekly => elapsed % 7 == 0,
            MeetingRecurrence::Fortnightly => elapsed % 14 == 0,
            MeetingRecurrence::Weekdays => !matches!(date.weekday(), Weekday::Sat | Weekday::Sun),
        }
    }
}

fn local_start(timezone: Tz, local: NaiveDateTime) -> Option<DateTime<Utc>> {
    match timezone.from_local_datetime(&local) {
        LocalResult::Single(start) => Some(start.with_timezone(&Utc)),
        LocalResult::Ambiguous(first, second) => Some(first.min(second).with_timezone(&Utc)),
        LocalResult::None => None,
    }
}

/// Return the channel-bound addressable-event `d` tag for a meeting.
pub fn meeting_identifier(channel_id: Uuid, meeting_id: Uuid) -> String {
    format!("{channel_id}:{meeting_id}")
}

/// Parse and validate a signed meeting event's envelope and JSON content.
///
/// Signature verification belongs to the transport. This validates exactly one
/// canonical UUID `h` tag and one `d` tag binding the address to that channel.
pub fn parse_channel_meeting(event: &Event) -> Result<ChannelMeeting, MeetingError> {
    if u32::from(event.kind.as_u16()) != KIND_CHANNEL_MEETING {
        return Err(MeetingError("event is not a channel meeting".into()));
    }
    if event.content.len() > MAX_MEETING_CONTENT_BYTES {
        return Err(MeetingError("meeting content exceeds 8192 bytes".into()));
    }
    meeting_revision(event)?;
    let channel = single_tag(event, "h")?;
    let channel_id = Uuid::parse_str(channel)
        .map_err(|_| MeetingError("meeting h tag must be a channel UUID".into()))?;
    let identifier = single_tag(event, "d")?;
    let (address_channel, meeting) = identifier
        .split_once(':')
        .ok_or_else(|| MeetingError("meeting d tag must be channel_uuid:meeting_uuid".into()))?;
    let meeting_id = Uuid::parse_str(meeting)
        .map_err(|_| MeetingError("meeting d tag must contain a meeting UUID".into()))?;
    if channel != channel_id.to_string()
        || address_channel != channel
        || identifier != meeting_identifier(channel_id, meeting_id)
    {
        return Err(MeetingError(
            "meeting address must be canonical and match its h tag".into(),
        ));
    }
    let definition: MeetingDefinition = serde_json::from_str(&event.content)
        .map_err(|error| MeetingError(format!("invalid meeting definition: {error}")))?;
    definition.validate()?;
    Ok(ChannelMeeting {
        channel_id,
        meeting_id,
        definition,
    })
}

fn single_tag<'a>(event: &'a Event, name: &str) -> Result<&'a str, MeetingError> {
    let mut matching = event
        .tags
        .iter()
        .map(|tag| tag.as_slice())
        .filter(|parts| parts.first().is_some_and(|part| part == name));
    let parts = matching
        .next()
        .ok_or_else(|| MeetingError(format!("meeting requires exactly one {name} tag")))?;
    if parts.len() != 2 || matching.next().is_some() {
        return Err(MeetingError(format!(
            "meeting requires exactly one two-element {name} tag"
        )));
    }
    Ok(&parts[1])
}

